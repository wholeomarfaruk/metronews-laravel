<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Str;

/**
 * Downloads the greeting card fonts (config/greeting_card.php "fonts") from Google Fonts
 * into public/fonts/greeting-card so the card page doesn't depend on Google at runtime.
 *
 * Output per font: public/fonts/greeting-card/{slug}.css + public/fonts/greeting-card/{slug}/*.woff2
 * Run again after adding a font to the config.
 */
class DownloadGreetingCardFonts extends Command
{
    protected $signature = 'greeting-card:fonts {--subsets=bengali,latin,latin-ext : Unicode subsets to keep}';

    protected $description = 'Download the greeting card fonts from Google Fonts and self-host them in public/fonts/greeting-card';

    // A modern browser UA makes Google return woff2 files split by unicode-range subset.
    private const USER_AGENT = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

    public function handle(): int
    {
        $subsets = array_filter(array_map('trim', explode(',', $this->option('subsets'))));
        $baseDir = public_path('fonts/greeting-card');
        File::ensureDirectoryExists($baseDir);
        $failed = false;

        foreach (config('greeting_card.fonts') as $family => $query) {
            $slug = Str::slug($family);
            $this->info("{$family} → fonts/greeting-card/{$slug}.css");

            $response = Http::withHeaders(['User-Agent' => self::USER_AGENT])
                ->timeout(30)
                ->get("https://fonts.googleapis.com/css2?family={$query}&display=swap");
            if (!$response->successful()) {
                $this->error("  Could not fetch CSS (HTTP {$response->status()})");
                $failed = true;
                continue;
            }

            // Google CSS: "/* subset */ @font-face { ... }" blocks.
            preg_match_all('#/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})#', $response->body(), $blocks, PREG_SET_ORDER);

            // Download into a temp folder; the existing font is only replaced if everything succeeds.
            $fontDir = "{$baseDir}/{$slug}";
            $tmpDir = "{$fontDir}.tmp";
            File::deleteDirectory($tmpDir);
            File::ensureDirectoryExists($tmpDir);

            $css = "/* {$family} — self-hosted from Google Fonts (SIL Open Font License). Generated by `php artisan greeting-card:fonts`. */\n";
            $files = []; // remote url => local file name (variable fonts reuse one file for several weights)
            $fontFailed = false;

            foreach ($blocks as [, $subset, $block]) {
                if (!in_array($subset, $subsets, true)) {
                    continue;
                }
                if (!preg_match('#url\((https://[^)]+)\)#', $block, $m)) {
                    continue;
                }
                $url = $m[1];

                if (!isset($files[$url])) {
                    preg_match('#font-weight:\s*([\d ]+);#', $block, $w);
                    $weight = str_replace(' ', '-', trim($w[1] ?? '400'));
                    $name = "{$slug}-{$weight}-{$subset}.woff2";

                    $font = Http::withHeaders(['User-Agent' => self::USER_AGENT])->timeout(60)->get($url);
                    if (!$font->successful()) {
                        $this->error("  Could not download {$name}");
                        $fontFailed = true;
                        break;
                    }
                    File::put("{$tmpDir}/{$name}", $font->body());
                    $files[$url] = $name;
                    $this->line(sprintf('  %-45s %6.1f KB', $name, strlen($font->body()) / 1024));
                }

                $css .= "/* {$subset} */\n" . str_replace($url, "{$slug}/{$files[$url]}", $block) . "\n";
            }

            if (!$files && !$fontFailed) {
                $this->error('  No matching font files found');
                $fontFailed = true;
            }
            if ($fontFailed) {
                File::deleteDirectory($tmpDir);
                $this->warn('  Kept the previously downloaded files (if any) for this font.');
                $failed = true;
                continue;
            }

            File::deleteDirectory($fontDir);
            File::moveDirectory($tmpDir, $fontDir);
            File::put("{$baseDir}/{$slug}.css", $css);
        }

        return $failed ? self::FAILURE : self::SUCCESS;
    }
}
